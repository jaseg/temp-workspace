"""sampler.kicad_sch: main sampler (design/lowcost/sim/sampler/RESULT.md, SPEC decisions 1-3).

Signal path, left to right:
  BUF_OUT_S (BUF802 OUT pin, input sheet) -> R201 10 R -> 4-diode bridge (D201, D202 = 2x BAT15-04W)
  -> hold node: C205 2.2 pF C0G -> U201 TPH2501 G = +3.0 (1.00 k / 499 R, +/-2.5 V)
  -> U202 TPH2501 inverting level shift on +3V3/GND (1 k / 1 k, +in = ADC_REF_MID 0.725 V)
  -> R211 33 R + C207 220 pF -> ADC_IN (J701 pin 3 on mcu_if, STM32G474 PA0).
Bridge rails: STRB_A / STRB_K (balun outputs, strobe sheet) -> 47 pF C0G -> node -> 24.9 R -> diodes;
bias VBIAS_A (-1.00 V) / VBIAS_K (+1.00 V) through 1 k into the node; 1 k across the balun outputs.

BAT15-04W (Infineon, SOT-323, series pair): pin 1 = anode D1, pin 2 = cathode D2, pin 3 = common
(cathode D1 / anode D2). Each package is one leg of the bridge: pin 1 on the anode rail, pin 2 on the
cathode rail, pin 3 on the input (D201) or the hold node (D202).
TPH2501-TR SOT-23-5 (3PEAK datasheet pin configuration): 1 OUT, 2 -Vs, 3 +IN, 4 -IN, 5 +Vs, the same as
the KiCad OPA197xDBV symbol, which is reused."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from schlib import g
from common import new_sheet, hier_pins, R, C

DUAL = "Device:D_Schottky_Dual_Series_AKC"          # 1 A, 2 K, 3 common
DUAL_FP = "Package_TO_SOT_SMD:SOT-323_SC-70"
BAT_F = {"Price": "0.37 USD @10 (SPEC)", "Note": "SOT-323: 1 A1, 2 K2, 3 K1/A2"}
OPA = "Amplifier_Operational:OPA197xDBV"           # 1 OUT, 2 V-, 3 +, 4 -, 5 V+  (= TPH2501 SOT-23-5)
OPA_FP = "Package_TO_SOT_SMD:SOT-23-5"
TPH_F = {"Price": "0.43 USD (LCSC)", "Note": "TPH2501 SOT-23-5: 1 OUT, 2 -Vs, 3 +IN, 4 -IN, 5 +Vs"}
TP = "Connector:TestPoint"
TP_FP = "TestPoint:TestPoint_Pad_D1.0mm"
T = 1.0      # annotation text size


def P(x, y):
    return (g(x), g(y))


def main():
    sh = new_sheet("sampler", comments=["Generated by gen/gen_sampler.py from design/lowcost/sim/sampler/RESULT.md.",
                                        "Bridge + hold node: one compact RF cluster next to the BUF802 (input sheet)."])

    # ------------------------------------------------------------------ input leg
    sh.hlabel("BUF_OUT_S", P(56, 90), "input", side="left")
    r10 = R(sh, "10", P(62, 90), rot=90, fields={"Note": "<= 3 mm from BUF802 OUT pin"})
    sh.wire(P(56, 90), r10["1"])

    # ------------------------------------------------------------------ diode bridge
    d1 = sh.add(DUAL, "D", "BAT15-04W", P(75, 90), rot=270, fp=DUAL_FP, lcsc="C5380972",
                mpn="BAT1504WH6327XTSA1", fields=BAT_F)
    d2 = sh.add(DUAL, "D", "BAT15-04W", P(91, 90), rot=270, mirror="y", fp=DUAL_FP, lcsc="C5380972",
                mpn="BAT1504WH6327XTSA1", fields=BAT_F)
    sh.wire(r10["2"], d1["3"])                                   # bridge input node
    # anode rail (top)
    sh.path([d1["1"], P(75, 80), P(91, 80), d2["1"]])
    ra = R(sh, "24.9", P(83, 75), fields={"Note": "rail resistor at the diodes (sim 25 R)"})
    sh.wire(ra["2"], P(83, 80))
    # cathode rail (bottom)
    sh.path([d1["2"], P(75, 100), P(91, 100), d2["2"]])
    rk = R(sh, "24.9", P(83, 105), fields={"Note": "rail resistor at the diodes (sim 25 R)"})
    sh.wire(rk["1"], P(83, 100))

    # strobe coupling: STRB_A / STRB_K -> 47 pF C0G -> rail node
    sh.hlabel("STRB_A", P(30, 66), "input", side="left")
    sh.hlabel("STRB_K", P(30, 114), "input", side="left")
    ca = C(sh, "47p", P(75, 66), rot=90, size="0402", lcsc="C1567", fields={"Note": "C0G"})
    ck = C(sh, "47p", P(75, 114), rot=90, size="0402", lcsc="C1567", fields={"Note": "C0G"})
    sh.wire(P(30, 66), ca["1"])
    sh.wire(P(30, 114), ck["1"])
    rt = R(sh, "1k", P(36, 90), fields={"Note": "across the balun outputs (sim Rterm)"})
    sh.wire(rt["1"], P(36, 66))
    sh.wire(rt["2"], P(36, 114))
    sh.path([ca["2"], P(83, 66), ra["1"]])
    sh.path([ck["2"], P(83, 114), rk["2"]])

    # bias feeds
    rba = R(sh, "1k", P(83, 57))
    sh.wire(rba["2"], P(83, 66))
    sh.path([rba["1"], P(83, 50), P(104, 50)])
    sh.hlabel("VBIAS_A", P(104, 50), "input", side="right")
    cba = C(sh, "10n", P(95, 53))
    sh.gnd(cba["2"])
    sh.wire(cba["1"], P(95, 50))
    rbk = R(sh, "1k", P(83, 123))
    sh.wire(rbk["1"], P(83, 114))
    sh.path([rbk["2"], P(83, 130), P(104, 130)])
    sh.hlabel("VBIAS_K", P(104, 130), "input", side="right")
    cbk = C(sh, "10n", P(95, 133))
    sh.gnd(cbk["2"])
    sh.wire(cbk["1"], P(95, 130))
    for net, y in (("VBIAS_A", 50), ("VBIAS_K", 130)):
        tp = sh.add(TP, "TP", net, P(100, y), fp=TP_FP)

    # ------------------------------------------------------------------ hold node + U201
    u1 = sh.add(OPA, "U", "TPH2501", P(122, 92), fp=OPA_FP, lcsc="C126713", mpn="TPH2501-TR", fields=TPH_F)
    sh.wire(d2["3"], u1["3"])                                    # hold node (y = 90)
    ch = C(sh, "2.2p", P(103, 93), size="0402", fields={"Note": "C0G, hold capacitor"})
    sh.gnd(ch["2"])
    sh.stub(u1, "5", "+2V5", kind="power")
    sh.power("-2V5", u1["2"], dy=g(4))
    sh.path([u1["4"], P(114, 94), P(114, 112)])
    rf1 = R(sh, "1.00k", P(122, 112), rot=90, lcsc="C11702", fields={"Note": "1 %"})
    sh.wire(P(114, 112), rf1["1"])
    sh.path([rf1["2"], P(130, 112), P(130, 92)])
    rg1 = R(sh, "499", P(114, 117), fields={"Note": "1 %"})
    sh.wire(P(114, 112), rg1["1"])
    sh.gnd(rg1["2"])
    sh.wire(u1["1"], P(139, 92))
    sh.add(TP, "TP", "HOLD_OUT", P(134, 92), fp=TP_FP)

    # ------------------------------------------------------------------ U202 level shifter
    rin = R(sh, "1k", P(142, 92), rot=90)
    u2 = sh.add(OPA, "U", "TPH2501", P(160, 90), fp=OPA_FP, lcsc="C126713", mpn="TPH2501-TR", fields=TPH_F)
    sh.wire(rin["2"], u2["4"])
    sh.stub(u2, "5", "+3V3", kind="power")
    sh.stub(u2, "2", "GND", kind="gnd")
    sh.path([P(150, 92), P(150, 104)])
    rf2 = R(sh, "1k", P(158, 104), rot=90)
    sh.wire(P(150, 104), rf2["1"])
    sh.path([rf2["2"], P(170, 104), P(170, 90)])
    sh.hlabel("ADC_REF_MID", P(140, 78), "input", side="left")
    sh.path([P(140, 78), P(152, 78), P(152, 88), u2["3"]])
    cref = C(sh, "10n", P(146, 81))
    sh.gnd(cref["2"])
    sh.wire(u2["1"], P(173, 90))
    sh.add(TP, "TP", "SHIFT_OUT", P(168, 90), fp=TP_FP)
    rs = R(sh, "33", P(176, 90), rot=90)
    sh.wire(P(173, 90), rs["1"])
    cad = C(sh, "220p", P(186, 93), fields={"Note": "C0G, at J701 pin 3"})
    sh.gnd(cad["2"])
    sh.wire(rs["2"], P(194, 90))
    sh.hlabel("ADC_IN", P(194, 90), "output", side="right")

    # ------------------------------------------------------------------ decoupling (one cap per supply pin)
    def dec(rail, x, y, note):
        c = C(sh, "100n", P(x, y))
        if rail.startswith("-"):
            sh.power("GND", c["1"], dy=-2.54, rot=180)
            sh.power(rail, c["2"], dy=g(4))
        else:
            sh.power(rail, c["1"], dy=-2.54)
            sh.power("GND", c["2"], dy=2.54)
        sh.text(note, (g(x) - 2.5, g(y) + g(10)), size=0.9)
        return c
    dec("+2V5", 112, 162, "U201.5")
    dec("-2V5", 124, 162, "U201.2")
    dec("+3V3", 136, 162, "U202.5")
    sh.text("Decoupling: 100 nF X7R 0402 within 1 mm of each supply pin\n"
            "(U202 V- is GND). Bulk on the power sheet.", P(108, 150), size=T)

    # ------------------------------------------------------------------ annotations
    sh.text("SAMPLER (sim/sampler/RESULT.md, SPEC decisions 1-3)\n"
            "Gain hold/input 0.69, efficiency 69 % per strobe; 10-90 % 109 ps behind the BUF802 (65 ps ideal step).\n"
            "Noise ~0.35 mV rms at the bridge input after deconvolution; pedestal +49 mV (null with rail CM via DACs).\n"
            "Software: x_k = (v_k - 0.31 v_(k-1)) / 0.48 (calibrate per board). No bootstrap.\n"
            "ADC trigger 40 ns after the strobe (any 0-212 ns settles), synchronous ADC clock; the ADC must sample\n"
            "BEFORE the S_STROBE falling edge (+160 ns): its reverse pulse shifts the hold by -13 mV (phase_array RESULT).",
            P(16, 14), size=T)
    sh.text("INPUT LEG: R201 0402 within 3 mm of the BUF802 OUT pin;\n"
            "R201 -> bridge input <= 3 mm (~18 ps), 0.36 mm trace\n"
            "over solid L2 GND. BUF_OUT_S is the BUF802 OUT node\n"
            "itself (49.9 R trigger leg is on the input sheet).\n"
            "Input network rings for ideal edges: keep it short.", P(40, 140), size=T)
    sh.text("STROBE: 50 % square from the balun (strobe sheet),\n"
            "shorted 80 ps stub -> ~130 ps pulse, 3 V class.\n"
            "STRB_A drives the anode rail (+ pulse), STRB_K\n"
            "the cathode rail (- pulse). Balun -> C201/C202\n"
            "<= 3 mm (~18 ps), 50 R, equal length (+/-0.1 mm);\n"
            "rail C mismatch 0.30/0.45 pF -> 30 mVpp kick at\n"
            "the trigger end.", P(16, 28), size=T)
    sh.text("BRIDGE: D201/D202 BAT15-04W, mirror-symmetric,\n"
            "both packages side by side, rails <= 2 mm.\n"
            "Rectified charge 1.75 pC (A) / 1.38 pC (K) per\n"
            "strobe; 47 pF rails recover in 47 ns.\n"
            "Strobe kick: 174 mVpp at bridge input,\n"
            "113 mVpp at BUF802 pin, 19 mVpp trigger end.", P(40, 150), size=T)
    sh.text("BIAS (mcu_if): VBIAS_A -0.50..-1.46 V (DAC/-2V5 divider,\n"
            "2.9k), VBIAS_K +0.2..+2.7 V (DAC via 5.1k): reverse-biases the\n"
            "bridge between strobes. 1 k x 47 pF: tau 47 ns.\n"
            "10 nF at the cold end of each 1 k feed.", P(108, 36), size=T)
    sh.text("HOLD NODE: C205 2.2 pF C0G + U201 Cin (1 pF CM) + pad.\n"
            "D202.3 -> C205 -> U201.3 < 2 mm, no via, no TP\n"
            "(leakage/C). Droop 1.25 % per 320 ns (model).\n"
            "U201: G = 1 + 1.00k/499 = +3.0 on +/-2.5 V:\n"
            "+/-0.35 V hold -> +/-1.04 V.", P(116, 120), size=T)
    sh.text("LEVEL SHIFT U202 (+3V3/GND):\n"
            "Vadc = 2 x 0.725 V - V(U201) = 1.45 V - V(U201)\n"
            "-> 0.41..2.49 V at PA0. U201+U202 settle ~20 ns.", P(158, 112), size=T)
    sh.text("ADC PIN: R211 33 R + C207 220 pF C0G placed at\n"
            "J701 pin 3 (mcu_if), PA0 ADC12_IN1, 6.5-cycle\n"
            "(108 ns) sampling at 60 MHz.", P(174, 70), size=T)

    names = {n for n, _ in hier_pins("sampler")}
    assert names == {"BUF_OUT_S", "STRB_A", "STRB_K", "VBIAS_A", "VBIAS_K", "ADC_REF_MID", "ADC_IN"}, names
    split_wires(sh)
    sh.save()


def split_wires(sh):
    """Split wires at every pin or wire end lying on their interior (kicad-cli only connects pins at
    wire ends), so T-junctions and pins placed on a wire are real connections."""
    pts = {p for w in sh.wires for p in w}
    for s in sh.symbols:
        for pd in s.pins:
            pts.add(s.pin(pd.number))
    out = []
    for a, b in sh.wires:
        inner = [p for p in pts if sh._on_mid(p, a, b)]
        inner.sort(key=lambda p: abs(p[0] - a[0]) + abs(p[1] - a[1]))
        chain = [a] + inner + [b]
        out += list(zip(chain, chain[1:]))
    sh.wires = out


def check(outdir):
    """Netlist of this sheet alone (kicad-cli) and the key connections."""
    import schlib
    n = schlib.nets(os.path.join(schlib.OUTDIR, "sampler.kicad_sch"), os.path.join(outdir, "sampler.net"))
    A = schlib.assert_net
    A(n, "BUF_OUT_S", {("R201", "1")})
    A(n, "STRB_A", {("C201", "1"), ("R204", "1")})
    A(n, "STRB_K", {("C202", "1"), ("R204", "2")})
    A(n, "VBIAS_A", {("R205", "1"), ("C203", "1")})
    A(n, "VBIAS_K", {("R206", "2"), ("C204", "1")})
    A(n, "ADC_REF_MID", {("U202", "3"), ("C206", "1")})
    A(n, "ADC_IN", {("R211", "2"), ("C207", "1")})
    on = lambda *m: next(k for k, v in n.items() if set(m) <= v)
    on(("R201", "2"), ("D201", "3"))                                  # bridge input
    on(("D201", "1"), ("D202", "1"), ("R202", "2"))                   # anode rail
    on(("D201", "2"), ("D202", "2"), ("R203", "1"))                   # cathode rail
    on(("C201", "2"), ("R202", "1"), ("R205", "2"))
    on(("C202", "2"), ("R203", "2"), ("R206", "1"))
    on(("D202", "3"), ("C205", "1"), ("U201", "3"))                   # hold node
    on(("U201", "4"), ("R207", "1"), ("R208", "1"))
    on(("U201", "1"), ("R207", "2"), ("R209", "1"))
    on(("U202", "4"), ("R209", "2"), ("R210", "1"))
    on(("U202", "1"), ("R210", "2"), ("R211", "1"))
    A(n, "+2V5", {("U201", "5")}); A(n, "-2V5", {("U201", "2")}); A(n, "+3V3", {("U202", "5")})
    print("sampler netlist checks OK")


if __name__ == "__main__":
    main()
    if "--check" in sys.argv:
        check(sys.argv[sys.argv.index("--check") + 1])
