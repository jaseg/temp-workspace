#!/usr/bin/env node
// Generate src/font/newstroke.js from KiCad's common/newstroke_font.cpp.
// Usage: node tools/gen-font.js <kicad-source-dir>
//
// Only the Latin, Greek, Cyrillic and common symbol ranges are kept (GPL-2.0-or-later part of
// the font; the CJK part is under the OFL and is not needed for silkscreen text).

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const RANGES = [[0x20, 0x24f], [0x370, 0x4ff], [0x2000, 0x22ff], [0x2300, 0x23ff], [0x25a0, 0x25ff], [0x2600, 0x26ff]];
const PLACEHOLDER = 'F^K[KFYFY[K[';

const src = readFileSync(join(process.argv[2] ?? '.cache/kicad-10.0', 'common/newstroke_font.cpp'), 'utf8');
const body = src.slice(src.indexOf('newstroke_font[] ='), src.indexOf('Skip to CJK'));
// Each glyph is one C string literal per line; consecutive code points from U+0020.
const glyphs = [...body.matchAll(/^\s*"((?:[^"\\]|\\.)*)",/gm)].map(m => m[1].replace(/\\(.)/g, '$1'));

const out = {};
glyphs.forEach((g, i) => {
  const cp = 0x20 + i;
  if (g !== PLACEHOLDER && RANGES.some(([a, b]) => cp >= a && cp <= b)) out[cp] = g;
});

writeFileSync('src/font/newstroke.js', `// Generated by tools/gen-font.js from KiCad's newstroke_font.cpp. Do not edit.
// Newstroke font: Copyright (C) 2010 Vladimir Uryvaev, Copyright The KiCad Developers.
// GPL-2.0-or-later. Glyphs are Hershey-style strings: two bound characters, then point pairs
// (coordinate = char code - 'R'), with " R" lifting the pen.
export const GLYPHS = ${JSON.stringify(out)};
`);
console.log(`${Object.keys(out).length} glyphs`);
