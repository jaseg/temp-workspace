"""Placeholder sheets for the four critical analog sheets (input, sampler, trigger_phase, strobe).
They contain only the hierarchical labels, so the project opens and the root netlist is complete.
A placeholder is (re)written only if the file is missing or is still a placeholder; once an agent's
gen_<sheet>.py has written the real sheet, this script leaves it alone."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from schlib import OUTDIR, g
from common import CRITICAL, new_sheet, SHEETS

MARK = "PLACEHOLDER sheet"


def make(name, force=False):
    fn = os.path.join(OUTDIR, name + ".kicad_sch")
    if os.path.exists(fn) and MARK not in open(fn).read() and not force:
        print(f"{name}: real sheet present, placeholder skipped")
        return
    sh = new_sheet(name)
    _t, _b, _p, left, right = SHEETS[name]
    y = g(20)
    for p in left:
        y += 2.54
        if p:
            sh.hlabel(p[0], (g(30), y), p[1], side="left")
    y2 = g(20)
    for p in right:
        y2 += 2.54
        if p:
            sh.hlabel(p[0], (g(150), y2), p[1], side="right")
    sh.text(f"{MARK}: to be generated by gen/gen_{name}.py (critical analog sheet).", (g(30), g(10)), size=2)
    sh.save()


if __name__ == "__main__":
    for n in CRITICAL:
        make(n, force="--force" in sys.argv)
