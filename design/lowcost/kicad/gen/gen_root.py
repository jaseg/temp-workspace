"""Root sheet scope-fe.kicad_sch: block arrangement of the seven sub-sheets. Each sheet pin gets a short
wire and a local label of the same name, so equal names connect across blocks."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import schlib
from schlib import Sheet, g
from common import SHEETS

# (x, y) of each block in grid units (A3: 420 x 297 mm = 330 x 233 grid)
POS = {"input": (25, 25), "sampler": (110, 25), "strobe": (195, 25), "mcu_if": (25, 100),
       "trigger_phase": (110, 100), "fpga_clock": (195, 100), "power": (270, 25)}
W = 40


def main():
    root = Sheet(None, title="scope-fe: low-cost 2 GHz equivalent-time sampling front end", ref_base=900,
                 comments=["Generated by gen/gen_root.py from design/lowcost/SPEC.md; do not edit by hand.",
                           "Sheet pins carry the SPEC net names; equal labels connect."])
    for name, (title, base, page, left, right) in SHEETS.items():
        x, y = POS[name]
        n = max(len(left), len(right), 2)
        conn = root.sheet(name, (g(x), g(y)), (g(W), g(2 * n + 4)), left, right, page=page)
        for net, p in conn.items():
            on_left = abs(p[0] - g(x)) < 0.01
            e = (p[0] - 5.08, p[1]) if on_left else (p[0] + 5.08, p[1])
            root.wire(p, e)
            root.label(net, e, rot=180 if on_left else 0)
        root.text(title, (g(x), g(y + 2 * n + 6)), size=1.0)
    root.text("Power rails are global power symbols (+5V, -5V, +3V3, +2V5, -2V5, +1V2, VBUS, GND) "
              "and do not appear as sheet pins.\nCMP_P/CMP_N are internal to trigger_phase.",
              (g(25), g(215)))
    root.save()


if __name__ == "__main__":
    main()
