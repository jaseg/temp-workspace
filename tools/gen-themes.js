#!/usr/bin/env node
// Generate src/theme/default-theme.js (KiCad's built-in default colour theme, in KiCad's own
// colour-theme JSON format) from common/settings/{color_settings.cpp,builtin_color_themes.h}.
// Usage: node tools/gen-themes.js <kicad-source-dir>

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(process.argv[2] ?? '.cache/kicad-10.0', 'common/settings');
const keys = new Map(
  [...readFileSync(join(dir, 'color_settings.cpp'), 'utf8').matchAll(/CLR\(\s*"([\w.]+)",\s*(\w+)\s*\)/g)].map(m => [m[2], m[1]]),
);
const header = readFileSync(join(dir, 'builtin_color_themes.h'), 'utf8');
const defaults = header.slice(header.indexOf('s_defaultTheme'), header.indexOf('s_copperColors'));

const theme = { meta: { name: 'KiCad Default', filename: '_builtin_default', version: 6 } };
for (const m of defaults.matchAll(/\{\s*(\w+),\s*CSS_COLOR\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)\s*\}/g)) {
  const key = keys.get(m[1]);
  if (!key || !/^(schematic|board)\./.test(key)) continue;
  let obj = theme;
  const path = key.split('.');
  for (const p of path.slice(0, -1)) obj = obj[p] ??= {};
  obj[path.at(-1)] = `rgba(${m[2]}, ${m[3]}, ${m[4]}, ${m[5]})`;
}

writeFileSync('src/theme/default-theme.js', `// Generated by tools/gen-themes.js from KiCad's builtin_color_themes.h. Do not edit.
// KiCad's built-in default colour theme, in KiCad's colour-theme JSON format.
export default ${JSON.stringify(theme, null, 1)};
`);
console.log(`${Object.keys(theme.schematic ?? {}).length} schematic + ${Object.keys(theme.board ?? {}).length} board keys`);
