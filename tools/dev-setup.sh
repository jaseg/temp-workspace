#!/usr/bin/env bash
# Set up a development environment in .venv:
#
#   * the plugin's runtime dependencies plus pytest
#   * kicad-python built from source against the API of the cached KiCad nightly
#     (released kicad-python does not have the schematic API yet)
#
# Requires uv (https://docs.astral.sh/uv/) and git.  Run tools/kicad-nightly.sh fetch first.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CACHE="$ROOT/.cache"
NIGHTLY_DIR="${KICAD_NIGHTLY_DIR:-$CACHE/kicad-nightly}"
KIPY_REF="${KIPY_REF:-main}"

version="$(cat "$NIGHTLY_DIR/VERSION")"            # kicad-nightly-10.99.0.6401.gf25b8c5aa4-x86_64.AppImage
commit="$(printf '%s' "$version" | sed -n 's/.*\.g\([0-9a-f]*\)-.*/\1/p')"
describe="$(printf '%s' "$version" | sed -n 's/kicad-nightly-\([0-9]*\.[0-9]*\.[0-9]*\)\.\([0-9]*\)\.g\([0-9a-f]*\)-.*/\1-\2-g\3/p')"
[ -n "$commit" ] || { echo "can't parse commit from $version" >&2; exit 1; }
echo "KiCad nightly $describe (commit $commit)"

mkdir -p "$CACHE"

# KiCad's API definitions at exactly the nightly's commit.
if [ ! -d "$CACHE/kicad-src/.git" ]; then
    git clone --filter=blob:none --no-checkout https://gitlab.com/kicad/code/kicad.git "$CACHE/kicad-src"
    git -C "$CACHE/kicad-src" sparse-checkout set api
fi
git -C "$CACHE/kicad-src" fetch --quiet origin
git -C "$CACHE/kicad-src" checkout --quiet "$commit"

# kicad-python sources
if [ ! -d "$CACHE/kicad-python/.git" ]; then
    git clone https://gitlab.com/kicad/code/kicad-python.git "$CACHE/kicad-python"
fi
git -C "$CACHE/kicad-python" fetch --quiet origin
git -C "$CACHE/kicad-python" checkout --quiet "origin/$KIPY_REF" 2>/dev/null || git -C "$CACHE/kicad-python" checkout --quiet "$KIPY_REF"

# protoc <= 25 (kicad-python's requirement) comes from grpcio-tools 1.62.
uv venv --quiet --allow-existing -p 3.11 "$CACHE/protoc-env"
uv pip install --quiet -p "$CACHE/protoc-env/bin/python" --only-binary :all: 'grpcio-tools==1.62.3' protoletariat
protoc="$CACHE/protoc-env/bin/protoc-wrapper"
printf '#!/bin/sh\nexec "%s" -m grpc_tools.protoc "$@"\n' "$CACHE/protoc-env/bin/python" > "$protoc"
chmod +x "$protoc"

proto_in="$CACHE/kicad-src/api/proto"
proto_out="$CACHE/kicad-python/kipy/proto"
mapfile -t srcs < <(cd "$proto_in" && find . -name '*.proto' | sed 's|^\./||' | sort)
(cd "$proto_in" && "$protoc" --python_out="$proto_out" --proto_path="$proto_in" \
    --experimental_allow_proto3_optional "${srcs[@]}")
(cd "$proto_in" && "$CACHE/protoc-env/bin/protol" --dont-create-package --in-place --exclude-google-imports \
    --python-out "$proto_out" protoc --protoc-path "$protoc" --experimental_allow_proto3_optional \
    --proto-path "$proto_in" "${srcs[@]}")
printf '# This file is automatically generated, do not modify it\nKICAD_API_VERSION = "%s"\n' "$describe" \
    > "$CACHE/kicad-python/kipy/kicad_api_version.py"

# Development venv: plugin deps, test deps, kicad-python from the source tree.
uv venv --quiet --allow-existing -p 3.11 "$ROOT/.venv"
uv pip install --quiet -p "$ROOT/.venv/bin/python" 'protobuf>=5.29.6,<6' 'pynng>=0.9,<0.10' \
    'jsonschema>=4.23,<5' 'zstandard>=0.25,<0.26' typing_extensions 'Pillow>=10' pytest
site="$("$ROOT/.venv/bin/python" -c 'import sysconfig; print(sysconfig.get_paths()["purelib"])')"
echo "$CACHE/kicad-python" > "$site/kicad-python-src.pth"
echo "$ROOT/plugin" > "$site/factorio-poles-plugin.pth"
"$ROOT/.venv/bin/python" -c 'import kipy.schematic, factorio_poles; print("ok: kipy", kipy.__file__)'
