def text_cells(text, color='#'):
    """The cells a line of sampler text covers: ([(col, row)], width), one cell gap between letters."""
    cells, x = [], 0
    for ch in text.upper():
        g = ALPHABET.get(ch) or ALPHABET['?']
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v != '.':
                    cells.append((x + c, r))
        x += len(g[0]) + 1
    return cells, max(0, x - 1)


def text_width(text):
    return text_cells(text)[1]


