def rotate(chart):
    """A chart turned a quarter clockwise."""
    rows = len(chart)
    return [''.join(chart[rows - 1 - r][c] for r in range(rows)) for c in range(len(chart[0]))]


def mirror(chart):
    return [row[::-1] for row in chart]


def flip(chart):
    return chart[::-1]
